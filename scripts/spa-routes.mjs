#!/usr/bin/env node
/**
 * The URL prefixes the SPA shell (dist/app.html) answers. Everything else that is not a real file gets
 * dist/404.html with a 404 status (no more "200 + home shell" for unknown URLs).
 *
 * Read from the app's own route tables: src/utils/index.ts (pagePathMap), the literal <Route path> in
 * src/App.jsx and LEGACY_REDIRECTS in src/config/routes.js. Prerendered pages ("/", /pricing, /register,
 * /login, /blog, legal) are files and are not listed.
 *
 *   node scripts/spa-routes.mjs          print the list
 *   node scripts/spa-routes.mjs --write  rewrite the catch-all in vercel.json, public/_redirects and
 *                                        netlify.toml, plus src/config/spa-routes.json (read by server/app.js)
 * tests/unit/spa-routes.test.mjs fails when the configs drift from the app's routes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
/** Served from prerendered files (or redirected), never by the SPA shell. */
const STATIC = new Set(['', 'pricing', 'register', 'login', 'blog', 'about', 'contact', 'privacy', 'terms', 'cookies',
  'cancellation', 'data-processing', 'data-security', 'accessibility']);

export function spaSegments() {
  const segs = new Set();
  const add = (p) => { const s = p.replace(/^\//, '').split('/')[0]; if (s && s !== '*' && !s.startsWith(':') && !STATIC.has(s)) segs.add(s); };
  for (const m of read('src/utils/index.ts').matchAll(/^\s*\w+:\s*'(\/[^']*)'/gm)) add(m[1]);
  for (const m of read('src/App.jsx').matchAll(/path="(\/[^"]*)"/g)) add(m[1]);
  for (const m of read('src/config/routes.js').matchAll(/from:\s*'(\/[^']*)'/g)) add(m[1]);
  return [...segs].sort();
}

const vercelRewrite = (segs) => ({ source: `/:seg(${segs.join('|')})/:rest*`, destination: '/app.html' });
const redirectsLines = (segs) => segs.flatMap((s) => [`/${s}    /app.html   200`, `/${s}/*    /app.html   200`]);

export function expected() {
  const segs = spaSegments();
  return { segs, vercel: vercelRewrite(segs), redirects: redirectsLines(segs) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { segs, vercel, redirects } = expected();
  if (!process.argv.includes('--write')) { console.log(segs.join('\n')); process.exit(0); }
  // vercel.json: the last rewrite is the SPA catch-all; unmatched URLs fall through to 404.html (404).
  const vj = JSON.parse(read('vercel.json'));
  vj.rewrites = vj.rewrites.filter((r) => r.destination !== '/app.html');
  vj.rewrites.push(vercel);
  fs.writeFileSync(path.join(ROOT, 'vercel.json'), `${JSON.stringify(vj, null, 2)}\n`);
  // Netlify: _redirects runs before netlify.toml; a non-forced 200 rewrite only applies when no file exists.
  const head = ['/    /index.html   200', '/pricing    /pricing/index.html   200',
    '/register    /register/index.html   200', '/login    /login/index.html   200',
    '/changelog    /   301', '/api-docs    /   301', '/book/*    /book.html   200'];
  fs.writeFileSync(path.join(ROOT, 'public/_redirects'), `${[...head, ...redirects, '/*    /404.html   404'].join('\n')}\n`);
  const nt = read('netlify.toml').replace(/\[\[redirects\]\][\s\S]*?status = 200\n/, `[[redirects]]
  from = "/*"
  to = "/404.html"
  status = 404
`).replace(/# SPA: serve the app shell[^\n]*\n(#[^\n]*\n)*/, `# The SPA shell (app.html) answers only the app's own routes (public/_redirects, generated by
# scripts/spa-routes.mjs); any other URL that is not a file gets 404.html with a 404 status.
`);
  fs.writeFileSync(path.join(ROOT, 'netlify.toml'), nt);
  fs.writeFileSync(path.join(ROOT, 'src/config/spa-routes.json'), `${JSON.stringify(segs, null, 2)}\n`);
  console.log(`wrote ${segs.length} SPA segments`);
}
