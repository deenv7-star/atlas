/** System prompt for one request. `mode`: 'text' | 'voice'. */
export function brainPrompt({ mode = 'text', today, page = '', owner = '' } = {}) {
  const style = mode === 'voice' ? VOICE_STYLE : TEXT_STYLE;
  const where = page ? `הבעלים פתחו את העוזר מתוך המסך ${String(page).slice(0, 60)}.` : '';
  return [
    ...CORE,
    ...style,
    `היום: ${heDay(today)} (${today}), אזור הזמן ישראל. ${where}${owner ? ` שם פרטי של הבעלים: ${owner}.` : ''}`.trim(),
    '',
    '=== תקציר המדריך של atlas (נבנה מהקוד; לפרטים: search_help) ===',
    kbDigest(mode === 'voice' ? 3600 : 5200),
    '=== סוף התקציר ===',
  ].join('\n');
}
